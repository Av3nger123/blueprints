import type { BlueprintManifest } from './types.js';

export const SKILL_MARKER = 'generated by scripts/build-registry.ts';

/**
 * A SKILL.md wrapper so the blueprint directory doubles as an Agent Skill. The skill tells the agent to
 * follow the blueprint's own read order and to run verification; it does not duplicate the content.
 */
export function renderSkill(m: BlueprintManifest): string {
  const description = truncate(
    `Use when implementing, adding, or auditing ${m.title.toLowerCase()} in an existing codebase. ${m.summary} ` +
      `Stacks: ${m.stacks.join(', ')}. Includes a runnable verification suite.`,
    1024,
  );
  const adapters = m.stacks.map((s) => `- \`adapters/${s}.md\``).join('\n');
  const env = m.verification.env
    .filter((e) => e.required)
    .map((e) => `${e.name}=<${e.name.toLowerCase().replace(/_/g, '-')}>`)
    .join(' ');
  const draft = m.status === 'draft'
    ? `\n> **Draft blueprint.** Tell the user it has not yet had maintainer review before you apply it.\n`
    : '';
  return `---
name: blueprint-${m.name}
description: ${JSON.stringify(description)}
---

<!-- ${SKILL_MARKER} from blueprint.yaml; do not edit by hand. -->

# ${m.title} (blueprint \`${m.name}\` v${m.version}, ${m.status})
${draft}
This skill packages an expert implementation blueprint. Follow it rather than improvising.

1. Read \`BLUEPRINT.md\` in full.
2. Read the adapter for the project's stack, if there is one:
${adapters}
3. Read \`verify/checklist.md\`.
4. Survey the codebase as described in "Integration into an existing codebase" before writing code.
5. Take the defaults in "Decisions & tradeoffs" unless the codebase or the user dictates otherwise, and record
   every deviation. Never violate a "Non-negotiable"; if a request conflicts with one, stop and ask.
6. When done, start the app and run the verification suite from this directory:

   \`\`\`bash
   ${env} ${m.verification.command}
   \`\`\`

   Then walk the \`[manual]\` checks in \`verify/checklist.md\`.
7. Report: decisions and deviations, files changed, the result of every check id (pass, fail, skipped with
   reason), and the manual checks the user still needs to confirm. Do not claim completion while an automated
   check fails.
`;
}

function truncate(s: string, max: number): string {
  return s.length <= max ? s : `${s.slice(0, max - 1)}…`;
}
